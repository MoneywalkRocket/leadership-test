// ── Insight templates based on score patterns ──
export function generateInsights(
  topFactors: { factor: string; score: number }[],
  bottomFactor: { factor: string; score: number },
  axes: { D1: number; D2: number; D3: number; D4: number }
): string[] {
  const insights: string[] = [];
  const top1 = topFactors[0]?.factor;
  const top2 = topFactors[1]?.factor;
  const bottom = bottomFactor.factor;

  // Top factor insight
  const topInsightMap: Record<string, string> = {
    II: "가치와 원칙 기반의 의사결정이 핵심 강점입니다. 팀은 당신의 일관성을 신뢰합니다.",
    IM: "비전을 통해 팀을 하나로 모으는 능력이 두드러집니다. 사람들이 '이유'를 알 때 더 강해집니다.",
    IS: "기존 틀을 깨고 새로운 가능성을 탐색하는 것이 자연스럽습니다. 혁신의 촉매제 역할을 합니다.",
    IC: "사람 한 명 한 명을 깊이 이해하고 맞춤 지원하는 것이 당신의 차별점입니다.",
    CR: "명확한 기대치와 공정한 보상 체계로 팀의 동력을 만들어냅니다.",
    MBEA: "리스크를 선제적으로 관리하고, 체계적 점검을 통해 품질을 보장합니다.",
    PA: "상황을 지켜보며 팀의 자생력을 키우는 인내심이 있습니다.",
    SV: "구성원의 성장과 행복이 곧 팀의 성과라는 철학이 체화되어 있습니다.",
  };
  if (top1 && topInsightMap[top1]) insights.push(topInsightMap[top1]);

  // Combination insight
  if (top1 === "IM" && top2 === "IS") {
    insights.push("비전 제시 + 실험 장려가 결합되어, 팀이 '왜' 새로운 시도를 해야 하는지 자연스럽게 이해합니다.");
  } else if (top1 === "IC" && top2 === "SV") {
    insights.push("개인 배려 + 서번트 리더십의 조합으로, 구성원들의 심리적 안전감과 소속감이 매우 높습니다.");
  } else if (top1 === "CR" && top2 === "MBEA") {
    insights.push("명확한 기준 + 체계적 관리의 조합으로, 팀의 예측 가능성과 안정성이 높습니다.");
  } else if (top2) {
    insights.push(`${topInsightMap[top2]?.split(".")[0] ?? top2} — 이것이 두 번째 강점 축입니다.`);
  }

  // Bottom factor warning
  const bottomWarningMap: Record<string, string> = {
    II: "원칙이나 가치를 명시적으로 전달하는 데 덜 신경 쓰는 편입니다. 팀이 방향감을 잃지 않도록 핵심 가치를 주기적으로 상기시키세요.",
    IM: "비전 공유보다 실행에 집중하는 경향이 있습니다. 팀 에너지가 떨어질 때 '왜 이걸 하는지'를 다시 연결해주세요.",
    IS: "검증된 방식을 선호하여, 새로운 시도에 보수적일 수 있습니다. 의도적으로 '다르게 해볼 것' 하나를 정해보세요.",
    IC: "개인별 맞춤 관심이 부족할 수 있습니다. 정기 1:1로 구성원의 니즈를 파악하세요.",
    CR: "기대치가 암묵적일 수 있습니다. 성과 기준과 보상을 명시적으로 공유하세요.",
    MBEA: "사전 점검보다 사후 대응에 가까울 수 있습니다. 최소한의 체크 포인트를 설정하세요.",
    PA: "적극적으로 개입하는 편이라 팀의 자율성이 줄어들 수 있습니다. 때로는 한 발 물러서 지켜보세요.",
    SV: "성과 중심이라 구성원의 감정적 니즈를 놓칠 수 있습니다. 의도적으로 '사람 먼저' 시그널을 보내세요.",
  };
  if (bottom && bottomWarningMap[bottom]) {
    insights.push(bottomWarningMap[bottom]);
  }

  // Axis balance insight
  if (Math.abs(axes.D1) < 0.3) {
    insights.push("비전과 실행의 균형이 잘 잡혀 있습니다. 상황에 따라 유연하게 전환할 수 있는 강점입니다.");
  }
  if (Math.abs(axes.D2) > 2) {
    insights.push(axes.D2 > 0
      ? "위임 성향이 매우 강합니다. 위기 상황에서는 의도적으로 개입 강도를 높이는 연습이 필요합니다."
      : "통제 성향이 매우 강합니다. 안정기에는 의도적으로 자율의 범위를 넓혀보세요.");
  }

  return insights;
}
